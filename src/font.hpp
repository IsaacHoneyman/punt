#include "types.hpp"

struct Glyph { byte rows[8]; };
struct Font { Glyph glyphs[128]; };

template<size_t N>
consteval Glyph glyph(const char (&art)[N]) {
    static_assert(N == 8 * 8 + 1, "Glyph must be 8 rows of 8 charcters");
    
    Glyph g{};
    for (size_t y = 0; y < 8; ++y) {
        for (size_t x = 0; x < 8; ++x) {
            char ch = art[y * 8 + x];
            if (ch == '#') g.rows[y] |= 0x80 >> x;
        }
    }
    return g;
}

